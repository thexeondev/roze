pub fn expand(keys: *Aes192, k: *const [24]u8) void {
    var i: usize = 0;

    while (i < 6) : (i += 1)
        keys.round_keys[i] = mem.readInt(u32, k[i * 4 ..][0..4], .big);

    while (i < 52) : (i += 1) {
        var temp = keys.round_keys[i - 1];
        if (i % 6 == 0) {
            temp = (temp << 8) | (temp >> 24);
            temp = subWord(temp);
            temp ^= rcon[(i / 6) - 1];
        }
        keys.round_keys[i] = keys.round_keys[i - 6] ^ temp;
    }
}

pub fn encrypt(keys: *const Aes192, buf: *[16]u8) void {
    addRoundKey(buf, keys.round_keys[0..4].*);

    var r: usize = 1;
    while (r < rounds) : (r += 1) {
        subBytes(buf);
        shiftRows(buf);
        mixColumns(buf);
        addRoundKey(buf, keys.round_keys[r * 4 ..][0..4].*);
    }

    subBytes(buf);
    shiftRows(buf);
    addRoundKey(buf, keys.round_keys[12 * 4 ..][0..4].*);
}

pub fn decrypt(keys: *const Aes192, block: *[block_size]u8) void {
    addRoundKey(block, keys.round_keys[12 * 4 ..][0..4].*);

    var r: usize = rounds - 1;
    while (r > 0) : (r -= 1) {
        invShiftRows(block);
        invSubBytes(block);
        addRoundKey(block, keys.round_keys[r * 4 ..][0..4].*);
        invMixColumns(block);
    }

    invShiftRows(block);
    invSubBytes(block);
    addRoundKey(block, keys.round_keys[0..4].*);
}

fn subWord(word: u32) u32 {
    const b0: u8 = @truncate((word >> 24) & 0xFF);
    const b1: u8 = @truncate((word >> 16) & 0xFF);
    const b2: u8 = @truncate((word >> 8) & 0xFF);
    const b3: u8 = @truncate(word & 0xFF);

    return (@as(u32, s_box[b0]) << 24) |
        (@as(u32, s_box[b1]) << 16) |
        (@as(u32, s_box[b2]) << 8) |
        (@as(u32, s_box[b3]));
}

fn addRoundKey(buf: *[16]u8, keys: [4]u32) void {
    for (0..4) |i| {
        const k = keys[i];
        buf[i * 4 + 0] ^= @truncate(k >> 24);
        buf[i * 4 + 1] ^= @truncate(k >> 16);
        buf[i * 4 + 2] ^= @truncate(k >> 8);
        buf[i * 4 + 3] ^= @truncate(k);
    }
}

fn subBytes(buf: *[16]u8) void {
    for (0..16) |i| buf[i] = s_box[buf[i]];
}

fn invSubBytes(buf: *[16]u8) void {
    for (0..16) |i| buf[i] = inv_s_box[buf[i]];
}

fn shiftRows(buf: *[16]u8) void {
    const tmp = buf.*;
    buf[1] = tmp[5];
    buf[5] = tmp[9];
    buf[9] = tmp[13];
    buf[13] = tmp[1];
    buf[2] = tmp[10];
    buf[6] = tmp[14];
    buf[10] = tmp[2];
    buf[14] = tmp[6];
    buf[3] = tmp[15];
    buf[7] = tmp[3];
    buf[11] = tmp[7];
    buf[15] = tmp[11];
}

fn invShiftRows(buf: *[16]u8) void {
    const tmp = buf.*;
    buf[1] = tmp[13];
    buf[5] = tmp[1];
    buf[9] = tmp[5];
    buf[13] = tmp[9];
    buf[2] = tmp[10];
    buf[6] = tmp[14];
    buf[10] = tmp[2];
    buf[14] = tmp[6];
    buf[3] = tmp[7];
    buf[7] = tmp[11];
    buf[11] = tmp[15];
    buf[15] = tmp[3];
}

inline fn xtime(x: u8) u8 {
    return if ((x & 0x80) != 0) (x << 1) ^ 0x1b else x << 1;
}

fn mixColumns(buf: *[16]u8) void {
    var i: usize = 0;
    while (i < 16) : (i += 4) {
        const s0 = buf[i + 0];
        const s1 = buf[i + 1];
        const s2 = buf[i + 2];
        const s3 = buf[i + 3];
        const tmp = s0 ^ s1 ^ s2 ^ s3;
        buf[i + 0] ^= tmp ^ xtime(s0 ^ s1);
        buf[i + 1] ^= tmp ^ xtime(s1 ^ s2);
        buf[i + 2] ^= tmp ^ xtime(s2 ^ s3);
        buf[i + 3] ^= tmp ^ xtime(s3 ^ s0);
    }
}

fn invMixColumns(buf: *[16]u8) void {
    var i: usize = 0;
    while (i < 16) : (i += 4) {
        const s0 = buf[i + 0];
        const s1 = buf[i + 1];
        const s2 = buf[i + 2];
        const s3 = buf[i + 3];

        const x2_0 = xtime(s0);
        const x2_1 = xtime(s1);
        const x2_2 = xtime(s2);
        const x2_3 = xtime(s3);
        const x4_0 = xtime(x2_0);
        const x4_1 = xtime(x2_1);
        const x4_2 = xtime(x2_2);
        const x4_3 = xtime(x2_3);
        const x8_0 = xtime(x4_0);
        const x8_1 = xtime(x4_1);
        const x8_2 = xtime(x4_2);
        const x8_3 = xtime(x4_3);

        buf[i + 0] = (x8_0 ^ x4_0 ^ x2_0) ^ (x8_1 ^ x2_1 ^ s1) ^ (x8_2 ^ x4_2 ^ s2) ^ (x8_3 ^ s3);
        buf[i + 1] = (x8_0 ^ s0) ^ (x8_1 ^ x4_1 ^ x2_1) ^ (x8_2 ^ x2_2 ^ s2) ^ (x8_3 ^ x4_3 ^ s3);
        buf[i + 2] = (x8_0 ^ x4_0 ^ s0) ^ (x8_1 ^ s1) ^ (x8_2 ^ x4_2 ^ x2_2) ^ (x8_3 ^ x2_3 ^ s3);
        buf[i + 3] = (x8_0 ^ x2_0 ^ s0) ^ (x8_1 ^ x4_1 ^ s1) ^ (x8_2 ^ s2) ^ (x8_3 ^ x4_3 ^ x2_3);
    }
}
